const DEFAULT_TIER = 3;

const tierByKey = new Map<string, number>();
for (const [tier, words] of Object.entries(tiers)) {
  for (const word of words) {
    const key = normalize(word);
    if (key) tierByKey.set(key, Number(tier));
  }
}

export const frequencyRank = (normalizedKey: string): number =>
  tierByKey.get(normalizedKey) ?? DEFAULT_TIER;
